#!/usr/bin/env python3
"""Emit the GL126 register tables as C++ for the SANE genesys backend.

Stage 2 of docs/sane-port.md: the Python driver replays captured phases
verbatim; the backend writes the same registers from generated tables.
This tool is the bridge. It reads `of135i/tables*.py` -- the single source
of truth, verified byte-exact against the USB captures -- and writes
`sane/gl126_tables.{h,cpp}`. Nothing here is hand-maintained: regenerate
after any table change, never edit the output.

What a phase becomes
--------------------
Each `Phase` is an ordered op stream (control writes, bulk writes, reads).
Only the writes carry state the backend must reproduce:

  * `cw` 0x40/0x04 wValue=0x0083 -- a register batch, `[reg][val]` pairs.
    These are flattened, in order, into one pair array per phase.
  * `cw` 0x40/0x04 wValue=0x0082 wIndex=1 -- a buffer descriptor,
    `[addr u32][len u32]`, followed by the `bo` ops carrying the payload.
    Emitted as an address/length record; the payload is either a slope
    table (emitted once, by name) or computed at run time (shading).
  * `cw` 0x40/0x0c -- end-of-access, emitted as its wValue/wIndex.

Reads and polls are deliberately NOT emitted into the pair tables.
Decision 3 in docs/sane-port.md: the C++ hooks poll explicitly with
timeouts rather than replaying the capture's pacing, so a captured read
is provenance, not behaviour. The generator counts them so the header can
state how many ops each phase covered.

Op programs (docs/sane-hook2-offset.md section 6)
--------------------------------------------------
The pair tables above lose three things hook 2 needs: transfer
boundaries, interleaving (a read between two writes), and the bulk
IN/OUT dance around a calibration read. For the phases hook 2/3/4 run
(`prep`, `afe_base`, `cal_dark_a`, `cal_dark_b`, `cal_white`,
`cal_gain_check_a`, `cal_gain_check_b`, `cal_shading_measure`,
`cal_shading_upload`, `cal_shading_verify`), every profile also gets one
or more ordered `OpProgram`s: one `Op` per captured transfer, in
captured order, kept one-to-one with `phase.ops` (or a contiguous slice
of it -- see "Split programs" below). The mapping (see `decode_ops`):

  * `cw`                                             -> `Write`
  * `cr` br=0x0c wv=0x008e wi=0x0020 length=1         -> `AckRead`
  * `cr` br=0x0c wv=0x008e wi=0x0018 length=1         -> `BulkDone`
  * `poll` wv=0x018e wi=0x0122 and resp[0] & 0x01     -> `PollDataReady`
  * `poll` wv=0x018e wi=0x0022 (reg 0x100)            -> `PollClass`
    (docs/sane-hook4-shading.md section 3, W2 -- the only site the
    vendor polls that register; the settled reply is kept as `data` and
    the runner waits for an upper-nibble class match against it)
  * every other `cr`/`poll`                           -> `Read`
  * `bi`                                              -> `BulkIn`
  * `bo`                                              -> `BulkOut` (bulk
    OUT of `len(op.data)` bytes to EP 0x02). A BulkOut COVERED by a bulk
    injection (see "Injection points" below) is emitted with `data =
    nullptr`: its captured chunk is the reference unit's own shading
    table -- calibration data of ONE unit -- and must never be written
    to another, the same principle as a register injection. Only the
    `len` survives. A BulkOut NOT covered by any injection keeps its
    captured payload as `data` (provenance/default); none of the phases
    emitted today has one -- the slope-table uploads in position/scan
    will, later.

`Read`/`AckRead`/`PollDataReady`/`PollClass`/`BulkDone` always carry the
captured reply as `data` (provenance, mirrored into a generated byte
blob); `Write` always carries its payload the same way; `BulkOut` does
too, EXCEPT when a bulk injection covers it (see above). `gl126_ops.cpp`
(the runner) polls `PollDataReady`/`PollClass` for real and fails closed
on a bad `AckRead`, a short `BulkIn`, or a short `BulkOut`; see
docs/sane-hook2-offset.md section 3 and docs/sane-hook4-shading.md
section 3.

Split programs (docs/sane-hook4-shading.md section 6)
-------------------------------------------------------
`cal_shading_verify` genuinely re-measures then re-uploads a table
computed from that measurement, so it cannot run as one program: its
own `phase.split_at` names the local op index of the re-upload's buffer
descriptor. It is emitted as TWO programs, `cal_shading_verify` (ops
`[0, split_at)`, the re-measurement) and `cal_shading_verify_upload`
(ops `[split_at, end)`, the re-upload), op indices in the second
re-based to 0 -- injection op indices are adjusted the same way.

Injection points
----------------
A phase's `injections` name the bytes that carry computed values (gain
codes, offset codes, FEEDL, line count, shading tables) instead of their
captured ones. Writing the captured byte instead would scan with
another unit's calibration, so each one is emitted as a named index (or
range of indices, for a bulk payload) into the phase's pair array. The
backend patches those entries before writing; it must not rely on the
captured value.

The same `injections` dict also feeds an OpInjection table on any phase
that gets an op program (see above): cal_gain_check_a's gain_r/gain_g/
gain_b (docs/sane-hook3-gain.md section 6, part A/2) address the op
program's own `ops` array directly -- op_index is the index into the
ORIGINAL captured op list, which is exactly the emitted op program's
index (one-to-one, asserted in op_injections_for()) -- unlike the pair-
table RegInjection above, which needs the op-index-to-pair-index
remapping decode_phase() computes.

A phase's `("bo", (op_indices...))` specs (the shading-table uploads)
instead feed an OpBulkInjection table: `{name, first_op, last_op}`, the
INCLUSIVE range of consecutive `BulkOut` ops the named payload is split
across (docs/sane-hook4-shading.md section 6) -- see
`op_bulk_injections_for()`. For a split program the range is re-based
the same way the ops themselves are.

Usage:  python tools/gen_sane_tables.py [--check]
        --check regenerates into memory and fails if the checked-in
        output differs (for the offline suite).
"""

