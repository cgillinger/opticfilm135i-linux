def test_offset_calibration_preflight_precedes_any_io():
    """The 'before first write' guarantee at the internal path (Astra
    review 2026-09-10): in offset_calibration (the first hook that
    writes), the geometry preflight -- the 1-kFrameMax frame check,
    feedl_for_frame(frame, profile) and frame_geometry(profile, frame) --
    precedes check_start_state()'s read AND the first write
    (write_table(dev, BASE_INIT...)). And the two functions it calls are
    pure (their gl126_ops.h signatures take only a frame and a Profile --
    no Genesys_Device, no Wire, no interface), so the preflight cannot
    itself do I/O: an out-of-range frame or a window past the travel
    ceiling throws before any transfer. This is the source-order proof of
    zero-writes-on-invalid-frame at the real hook; the runtime probe/holder
    checks above prove the throw itself.

    (A live genesys-testsuite test that constructs a Genesys_Device with a
    fake IUsbDevice and calls offset_calibration was assessed and judged
    disproportionate: gl126 writes go through its own UsbWire ->
    dev->interface->get_usb_device(), no testsuite precedent constructs a
    device+interface+hook, and the preflight is pure-and-first so
    zero-writes holds by construction. See the Astra report.)"""
    # The preflight itself now lives in validate_scan_request() (WP-4:
    # the magazine's load half needs the SAME refusals, and it runs
    # EARLIER than calibration -- see the companion test below). What
    # this test pins is unchanged: the whole refusal set precedes the
    # first device read and the first write, at the first hook that
    # writes.
    preflight = _validate_scan_request_body()
    for needle in ("frame < 1 || frame > kFrameMax",
                   "frame < 1 || frame > kSlideOpeningMax",
                   "profile->slides == nullptr",
                   "feedl_for_frame(frame, *profile, holder)",
                   "frame_geometry(*profile, frame, holder)"):
        assert needle in preflight, (needle, "missing from validate_scan_request")
    # And it is write-free by construction: no device I/O in its body.
    for banned in ("interface->", "check_start_state", "write_table",
                   "run_program", "run_phase_program"):
        assert banned not in preflight, (banned, "validate_scan_request must not do I/O")

    body = _offset_calibration_body()
    i_validate = body.index("validate_scan_request(dev)")
    i_state = body.index("check_start_state(dev)")   # first device read
    i_write = body.index("write_table(dev, BASE_INIT")  # first device write

    assert i_validate < i_state, ("preflight must precede the state read",
                                  i_validate, i_state)
    assert i_validate < i_write, ("preflight must precede the first write",
                                  i_validate, i_write)
    assert i_state < i_write, (i_state, i_write)

    ops_h = GL126_OPS_H.read_text()
    # Pure signatures: frame + Profile (+ the holder enum) only, no
    # device/Wire/interface.
    assert "feedl_for_frame(unsigned frame, const Profile& profile,\n" \
           "                         HolderKind holder = HolderKind::Strip)" in ops_h, ops_h[:0]
    assert "frame_geometry(const Profile& profile, unsigned frame,\n" \
           "                             HolderKind holder = HolderKind::Strip)" in ops_h
    for banned in ("Genesys_Device", "Wire", "interface"):
        # neither declaration line may mention a device/wire type
        for line in ops_h.splitlines():
            if "feedl_for_frame(" in line or "frame_geometry(" in line:
                assert banned not in line, (line, banned)
    print("test_offset_calibration_preflight_precedes_any_io OK "
          "(validate_scan_request precedes the state read and BASE_INIT; "
          "its own body does no I/O; feedl_for_frame/frame_geometry are pure)")


def test_load_document_is_pure_and_never_moves_the_magazine():
    """WP-5 (docs/sane-wp5-load-button.md section 3.4) retired the concern
    Astra's 2026-09-13 review raised about WP-4's load_document(): that
    hook used to run BEFORE calibration and drive the loader motor, so an
    impossible scan request could move the magazine before being refused.
    Since WP-5, load_document() (magazine_check_scan_allowed()) is the
    checker ITSELF that no longer moves anything -- it is pure computation
    on the in-process state and the on-disk mark, plus (review round two,
    finding J, 2026-09-27) exactly ONE device READ, reg 0x01, so a power
    cycle since Load film/Eject film last ran does not leave a stale
    Loaded/Failed claim un-refuted. No WRITE of any kind, no op program,
    no validate_scan_request() call either (there is no scan request to
    protect the magazine from any more, since nothing here can move it in
    the first place). The scan request's own refusals still run,
    unchanged, inside offset_calibration() at the actual scan. The
    status-line GET (magazine_state_text()) does NOT do even this one
    read -- it stays free of hardware reads by design; only this hook and
    Check status ever read reg 0x01 outside of a button press.

    Source-level, like the offset-calibration test above: the function
    body contains none of the device-WRITE primitives every OTHER
    magazine hook uses, and no motor-program runner. The runtime proof
    that a pending mark still refuses (with the mark kept), and that a
    cold read resets a stale claim, is tests/test_sane_magazine.py."""
    body = _magazine_check_scan_allowed_body()
    for banned in ("run_magazine_program", "run_phase_program",
                   "write_table", "validate_scan_request",
                   "check_start_state", "write_register", "write_registers",
                   "write_0x8c", "write_buffer", "write_gamma", "write_ahb",
                   "write_fe_register", "bulk_"):
        assert banned not in body, (banned, "magazine_check_scan_allowed must not do I/O")
    # The one read it IS allowed: reg 0x01, and only that register.
    assert body.count("read_register") == 1, body
    assert "read_register(REG_0x01)" in body, body
    # And it still runs before ANY of the ops that do -- the one place
    # that still moves the magazine is a SEPARATE function now.
    load_film = _magazine_load_film_body()
    assert 'run_magazine_program(dev, "load"' in load_film, load_film
    assert 'run_magazine_program(dev, "open"' in load_film, load_film
    print("test_load_document_is_pure_and_never_moves_the_magazine OK "
          "(no device I/O in load_document; the motor moves live in Load film alone)")


def test_public_frame_option_constraint_is_1_to_6():
    """The 'before first write' guarantee at the PUBLIC path: the SANE
    frontend enforces OPT_FRAME's constraint before any backend hook runs,
    so `scanimage --frame 0` / `--frame 7` are rejected without a single
    transfer. The integration patch declares gl126_frame_range = [1,
    kFrameMax] and binds it to OPT_FRAME as a SANE_CONSTRAINT_RANGE;
    kFrameMax is 6."""
    patch = PATCH.read_text()
    assert "static const SANE_Range gl126_frame_range" in patch
    m = re.search(r"gl126_frame_range\s*=\s*\{.*?1,.*?gl126::kFrameMax",
                  patch, re.DOTALL)
    assert m, "gl126_frame_range must run [1, kFrameMax]"
    assert "OPT_FRAME].constraint_type = SANE_CONSTRAINT_RANGE" in patch
    assert "OPT_FRAME].constraint.range = &gl126_frame_range" in patch
    assert "kFrameMax = 6" in GL126_H.read_text()
    # The "holder" option (issue #70): a STRING_LIST of strip/slide, and
    # while slide is set OPT_FRAME's range is gl126_slide_range = [1,
    # kSlideOpeningMax]; kSlideOpeningMax is 4 in gl126.h, and
    # gl126_ops.h's own mirror kFeedlSlideMax is 4 too. So scanimage
    # --holder slide --frame 5 is clamped by SANE core before any hook
    # runs (tests/test_sane_magazine.py exercises that path live).
    assert "static const SANE_Range gl126_slide_range" in patch
    m2 = re.search(r"gl126_slide_range\s*=\s*\{.*?1,.*?gl126::kSlideOpeningMax",
                   patch, re.DOTALL)
    assert m2, "gl126_slide_range must run [1, kSlideOpeningMax]"
    assert 'OPT_HOLDER].name = "holder"' in patch
    assert "OPT_HOLDER].constraint_type = SANE_CONSTRAINT_STRING_LIST" in patch
    assert "OPT_HOLDER].constraint.string_list = gl126_holder_list" in patch
    assert re.search(r'GL126_HOLDER_STRIP "strip"', patch) and \
        re.search(r'GL126_HOLDER_SLIDE "slide"', patch), "holder values strip/slide"
    assert "slide ? &gl126_slide_range" in patch, "holder switch must swap the frame range"
    assert "settings.slide_holder = (s->holder == " in patch
    assert "kSlideOpeningMax = 4" in GL126_H.read_text()
    assert "kFeedlSlideMax = 4" in GL126_OPS_H.read_text()
    print("test_public_frame_option_constraint_is_1_to_6 OK "
          "(OPT_FRAME SANE_CONSTRAINT_RANGE [1,6]; scanimage rejects 0/7 "
          "before any hook)")


